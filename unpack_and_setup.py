def unpack_project(target_dir: Path, zip_path: Path) -> None:
    """Распаковывает проект из внешнего ZIP-файла или из встроенного в скрипт архива."""
    target_dir.mkdir(parents=True, exist_ok=True)

    if zip_path.exists():
        print(f"[1/4] Найден внешний архив: {zip_path.resolve()}")
        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(target_dir)
    else:
        print("[1/4] Внешний ZIP не найден — извлекаю встроенный архив из самого распаковщика...")
        raw_bytes = base64.b64decode(EMBEDDED_ZIP_BASE64)
        # Также сохраняем сам .zip файл рядом для удобства
        zip_path.write_bytes(raw_bytes)
        print(f"      Создан архив: {zip_path.resolve()}")
        with zipfile.ZipFile(io.BytesIO(raw_bytes), "r") as zf:
            zf.extractall(target_dir)

    print(f"      Все файлы успешно распакованы в: {target_dir.resolve()}")


def setup_env_file(target_dir: Path) -> None:
    """Создаёт файл .env из .env.example, если он ещё не существует."""
    env_example = target_dir / ".env.example"
    env_file = target_dir / ".env"
    if env_example.exists() and not env_file.exists():
        shutil.copyfile(env_example, env_file)
        print("[2/4] Создан файл конфигурации .env (укажите в нём ваш BOT_TOKEN от @BotFather).")
    else:
        print("[2/4] Файл конфигурации .env готов.")


def setup_git_repository(target_dir: Path) -> None:
    """Инициализирует Git и настраивает remote origin на репозиторий пользователя."""
    if not shutil.which("git"):
        print("[3/4] Утилита git не найдена в системе (пропускаю git init).")
        return

    print(f"[3/4] Настройка Git и привязка к {REPO_URL}...")
    try:
        subprocess.run(["git", "init", "-b", "main"], cwd=target_dir, check=True)
        subprocess.run(["git", "add", "."], cwd=target_dir, check=True)
        subprocess.run(
            ["git", "commit", "-m", "feat: initial implementation of find_job_in_www_bot"],
            cwd=target_dir,
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        subprocess.run(
            ["git", "remote", "remove", "origin"],
            cwd=target_dir,
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        subprocess.run(
            ["git", "remote", "add", "origin", REPO_URL],
            cwd=target_dir,
            check=True,
        )
        print("      Git-репозиторий инициализирован, remote origin привязан.")
    except Exception as exc:
        print(f"      Предупреждение при настройке Git: {exc}")


